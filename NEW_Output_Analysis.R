calculate_import_trade_summary <- function(year_results, year) {
  REF <- year_results$REF

  ref_dom_rec <- as.numeric(get_domestic_recurrent_demand(REF))
  ref_imp_rec <- as.numeric(get_imported_recurrent_demand(REF))
  ref_finished_imports <- sum(REF$Y_imp_FCE[BIO])
  ref_exports <- sum(REF$exports[BIO])

  out <- lapply(
    scenario_names,
    function(scenario_name) {
      scenario <- year_results[[scenario_name]]

      dom_rec <- as.numeric(get_domestic_recurrent_demand(scenario))
      imp_rec <- as.numeric(get_imported_recurrent_demand(scenario))

      dom_cap <- as.numeric(get_domestic_capex_level_from_coefficients(scenario))
      imp_cap <- as.numeric(get_imported_capex_level_from_coefficients(scenario))

      recurrent_domestic <- sum(dom_rec)
      recurrent_imported <- sum(imp_rec)
      recurrent_total <- recurrent_domestic + recurrent_imported

      capex_domestic <- sum(dom_cap)
      capex_imported <- sum(imp_cap)
      capex_total <- capex_domestic + capex_imported

      finished_imports <- sum(scenario$Y_imp_FCE[BIO])
      exports <- sum(scenario$exports[BIO])

      data.frame(
        year = as.integer(year),
        scenario = scenario_name,

        recurrent_domestic_input_level = recurrent_domestic,
        recurrent_imported_input_level = recurrent_imported,
        recurrent_import_share =
          safe_ratio(recurrent_imported, recurrent_total),
        recurrent_import_change_vs_REF =
          recurrent_imported - sum(ref_imp_rec),

        domestic_CAPEX_input_level = capex_domestic,
        imported_CAPEX_input_level = capex_imported,
        CAPEX_import_share =
          safe_ratio(capex_imported, capex_total),
        imported_CAPEX_change_vs_REF =
          capex_imported - sum(get_imported_capex_level_from_coefficients(REF)),

        finished_biofuel_imports = finished_imports,
        finished_biofuel_import_change_vs_REF =
          finished_imports - ref_finished_imports,

        biofuel_exports = exports,
        biofuel_export_change_vs_REF =
          exports - ref_exports,

        net_finished_biofuel_imports =
          finished_imports - exports,

        recurrent_domestic_input_change_vs_REF =
          recurrent_domestic - sum(ref_dom_rec)
      )
    }
  )

  do.call(rbind, out)
}

