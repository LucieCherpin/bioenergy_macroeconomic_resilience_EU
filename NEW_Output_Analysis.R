# ===================================================================
# 11B. SCENARIO-INTERNAL UPSTREAM OUTPUT STRUCTURE
#      FEEDSTOCK / OPEX / CAPEX
#
# This is NOT a scenario-vs-REF decomposition.
# It measures the absolute domestic upstream NONBIO output requirements
# associated with the technology and production structure of S1/S2/S3.
#
# CAPEX is therefore used at its absolute annualized level, NOT as
# GFCF_capex_delta relative to 2023.
# ===================================================================


calculate_channel_output_structure <- function(
    scenario,
    year,
    scenario_name
) {

  # ---------------------------------------------------------------
  # NONBIO production structure
  # ---------------------------------------------------------------

  A_NN <-
    scenario$A_dom_tech[
      NONBIO,
      NONBIO,
      drop = FALSE
    ]

  L_NN <-
    solve(
      base::diag(length(NONBIO)) -
        A_NN
    )


  # ---------------------------------------------------------------
  # 1. DIRECT FEEDSTOCK-DRIVEN NONBIO DEMAND
  # ---------------------------------------------------------------

  feedstock_direct <-
    scenario$A_feed_dom_tech[
      NONBIO,
      BIO,
      drop = FALSE
    ] %*%
    scenario$X_bio[BIO]


  # ---------------------------------------------------------------
  # 2. DIRECT OPEX-DRIVEN NONBIO DEMAND
  # ---------------------------------------------------------------

  opex_direct <-
    scenario$A_opex_dom_tech[
      NONBIO,
      BIO,
      drop = FALSE
    ] %*%
    scenario$X_bio[BIO]


  # ---------------------------------------------------------------
  # 3. DIRECT CAPEX-DRIVEN NONBIO DEMAND
  #
  # IMPORTANT:
  # absolute annualized CAPEX level, NOT delta vs 2023
  # ---------------------------------------------------------------

  capex_direct <-
    scenario$A_capex_dom_tech[
      NONBIO,
      BIO,
      drop = FALSE
    ] %*%
    scenario$X_bio[BIO]


  # ---------------------------------------------------------------
  # CHECK:
  # Feedstock + OPEX must reproduce recurrent BIO-driven demand
  # ---------------------------------------------------------------

  recurrent_direct <-
    scenario$A_dom_tech[
      NONBIO,
      BIO,
      drop = FALSE
    ] %*%
    scenario$X_bio[BIO]

  stopifnot(
    isTRUE(
      all.equal(
        as.numeric(feedstock_direct + opex_direct),
        as.numeric(recurrent_direct),
        tolerance = 1e-10
      )
    )
  )


  # ---------------------------------------------------------------
  # PROPAGATE THROUGH NONBIO SUPPLY CHAINS
  # ---------------------------------------------------------------

  feedstock_total <-
    as.numeric(
      L_NN %*%
        feedstock_direct
    )

  opex_total <-
    as.numeric(
      L_NN %*%
        opex_direct
    )

  capex_total <-
    as.numeric(
      L_NN %*%
        capex_direct
    )


  # ---------------------------------------------------------------
  # FIRST-ORDER VALUES
  # ---------------------------------------------------------------

  feedstock_first <-
    as.numeric(feedstock_direct)

  opex_first <-
    as.numeric(opex_direct)

  capex_first <-
    as.numeric(capex_direct)


  # ---------------------------------------------------------------
  # HIGHER-ORDER VALUES
  # ---------------------------------------------------------------

  feedstock_higher <-
    feedstock_total -
    feedstock_first

  opex_higher <-
    opex_total -
    opex_first

  capex_higher <-
    capex_total -
    capex_first


  # ---------------------------------------------------------------
  # AGGREGATE OUTPUT REQUIREMENTS
  # ---------------------------------------------------------------

  feedstock_output <-
    sum(feedstock_total)

  opex_output <-
    sum(opex_total)

  capex_output <-
    sum(capex_total)

  total_upstream_output <-
    feedstock_output +
    opex_output +
    capex_output


  # Domestic BIO production level
  total_bio_output <-
    sum(
      scenario$X_bio[BIO]
    )


  # ---------------------------------------------------------------
  # RETURN AGGREGATE RESULT
  # ---------------------------------------------------------------

  data.frame(

    year = as.integer(year),

    scenario = scenario_name,

    BIO_output_level =
      total_bio_output,


    # First-order activation
    feedstock_first_order_output =
      sum(feedstock_first),

    opex_first_order_output =
      sum(opex_first),

    capex_first_order_output =
      sum(capex_first),


    # Higher-order activation
    feedstock_higher_order_output =
      sum(feedstock_higher),

    opex_higher_order_output =
      sum(opex_higher),

    capex_higher_order_output =
      sum(capex_higher),


    # Total upstream output requirement
    feedstock_total_output =
      feedstock_output,

    opex_total_output =
      opex_output,

    capex_total_output =
      capex_output,

    total_upstream_output =
      total_upstream_output,


    # Composition shares
    feedstock_share =
      safe_ratio(
        feedstock_output,
        total_upstream_output
      ),

    opex_share =
      safe_ratio(
        opex_output,
        total_upstream_output
      ),

    capex_share =
      safe_ratio(
        capex_output,
        total_upstream_output
      ),


    # Output requirement per EUR of domestic BIO output
    feedstock_output_per_eur_BIO =
      safe_ratio(
        feedstock_output,
        total_bio_output
      ),

    opex_output_per_eur_BIO =
      safe_ratio(
        opex_output,
        total_bio_output
      ),

    capex_output_per_eur_BIO =
      safe_ratio(
        capex_output,
        total_bio_output
      ),

    total_upstream_output_per_eur_BIO =
      safe_ratio(
        total_upstream_output,
        total_bio_output
      )
  )
}


