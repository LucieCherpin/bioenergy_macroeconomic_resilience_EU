# 6. PAIRWISE SCENARIO COMPARISONS: OUTPUT AND GVA
# ===================================================================

calculate_pairwise_macro <- function(year_results, year) {
  comparisons <- list(
    "S2-S1" = c("S2", "S1"),
    "S3-S1" = c("S3", "S1"),
    "S3-S2" = c("S3", "S2")
  )

  out <- lapply(
    names(comparisons),
    function(comparison_name) {
      high_name <- comparisons[[comparison_name]][1]
      low_name  <- comparisons[[comparison_name]][2]

      high <- year_results[[high_name]]
      low  <- year_results[[low_name]]

      delta_X   <- high$X   - low$X
      delta_GVA <- high$GVA - low$GVA

      data.frame(
        year = as.integer(year),
        comparison = comparison_name,
        total_output_difference = sum(delta_X),
        bio_output_difference = sum(delta_X[BIO]),
        nonbio_output_difference = sum(delta_X[NONBIO]),
        total_GVA_difference = sum(delta_GVA),
        bio_GVA_difference = sum(delta_GVA[BIO]),
        nonbio_GVA_difference = sum(delta_GVA[NONBIO])
      )
    }
  )

  do.call(rbind, out)
}

pairwise_macro_all <- do.call(
