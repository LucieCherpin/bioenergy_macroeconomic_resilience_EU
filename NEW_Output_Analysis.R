# Direct recurrent domestic demand generated by BIO production.
get_domestic_recurrent_demand <- function(endpoint) {
  endpoint$A_dom_tech[, BIO, drop = FALSE] %*%
    endpoint$X_bio[BIO]
}

# Direct domestic FEEDSTOCK demand generated by BIO production.
get_domestic_feedstock_demand <- function(endpoint) {

  endpoint$A_feed_dom_tech[, BIO, drop = FALSE] %*%
    endpoint$X_bio[BIO]
}


# Direct domestic OPEX demand generated by BIO production.
get_domestic_opex_demand <- function(endpoint) {

  endpoint$A_opex_dom_tech[, BIO, drop = FALSE] %*%
    endpoint$X_bio[BIO]
}


# Direct recurrent imported-input demand generated by BIO production.
get_imported_recurrent_demand <- function(endpoint) {
  endpoint$A_imp_tech[, BIO, drop = FALSE] %*%
    endpoint$X_bio[BIO]
}

get_imported_feedstock_demand <- function(endpoint) {

  endpoint$A_feed_imp_tech[, BIO, drop = FALSE] %*%
