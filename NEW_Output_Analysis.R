        scenario$X_bio[ADV_BIO]

      capex_ref <-
        REF$A_capex_dom_tech[NONBIO, ADV_BIO, drop = FALSE] %*%
        REF$X_bio[ADV_BIO]

      recurrent_shock <- as.numeric(recurrent_scenario - recurrent_ref)
      capex_shock <- as.numeric(capex_scenario - capex_ref)
      direct_shock <- recurrent_shock + capex_shock

      recurrent_total <- as.numeric(L_NN %*% recurrent_shock)
      capex_total <- as.numeric(L_NN %*% capex_shock)
      total_effect <- recurrent_total + capex_total

      data.frame(
        year = as.integer(year),
        scenario = scenario_name,
        sector_id = NONBIO,
        sector = sector_names[NONBIO],

        advanced_recurrent_first_order_effect = recurrent_shock,
        advanced_capex_first_order_effect = capex_shock,
        advanced_first_order_effect = direct_shock,

        advanced_recurrent_total_effect = recurrent_total,
        advanced_capex_total_effect = capex_total,
        advanced_total_output_effect = total_effect,

        advanced_higher_order_effect = total_effect - direct_shock
      )
    }
  )

  do.call(rbind, out)
}

