calculate_capex_summary <- function(year_results, year) {
  REF <- year_results$REF

  ref_dom_level <- sum(REF$GFCF_capex_level[NONBIO])
  ref_imp_level <- sum(REF$CAPEX_imp_leakage[NONBIO])

  out <- lapply(
    scenario_names,
    function(scenario_name) {
      scenario <- year_results[[scenario_name]]

      dom_level <- sum(scenario$GFCF_capex_level[NONBIO])
      dom_delta <- sum(scenario$GFCF_capex_delta[NONBIO])
      imp_level <- sum(scenario$CAPEX_imp_leakage[NONBIO])
      imp_delta <- imp_level - ref_imp_level

      total_level <- dom_level + imp_level
      total_delta <- dom_delta + imp_delta

      data.frame(
        year = as.integer(year),
        scenario = scenario_name,

        domestic_CAPEX_level = dom_level,
        domestic_CAPEX_delta_vs_2023 = dom_delta,
        imported_CAPEX_level = imp_level,
        imported_CAPEX_delta_vs_2023 = imp_delta,
        total_CAPEX_level = total_level,
        total_CAPEX_delta_vs_2023 = total_delta,

        domestic_CAPEX_share = safe_ratio(dom_level, total_level),
        imported_CAPEX_share = safe_ratio(imp_level, total_level),

        REF_domestic_CAPEX_level = ref_dom_level,
        REF_imported_CAPEX_level = ref_imp_level
      )
    }
  )

  do.call(rbind, out)
}

