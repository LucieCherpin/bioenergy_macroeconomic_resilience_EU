calculate_biofuel_NONBIO_contributions <- function(year_results, year) {
  REF <- year_results$REF

  A_NN_ref <- REF$A_dom_tech[NONBIO, NONBIO, drop = FALSE]
  L_NN <- solve(base::diag(length(NONBIO)) - A_NN_ref)

  out <- list()
  counter <- 1

  for (scenario_name in scenario_names) {
    scenario <- year_results[[scenario_name]]

    stopifnot(
      isTRUE(
        all.equal(
          scenario$A_dom_tech[NONBIO, NONBIO, drop = FALSE],
          A_NN_ref,
          tolerance = 1e-10
        )
      )
    )

    for (bio_sector in BIO) {
      recurrent_shock <-
        scenario$A_dom_tech[NONBIO, bio_sector] *
          scenario$X_bio[bio_sector] -
        REF$A_dom_tech[NONBIO, bio_sector] *
          REF$X_bio[bio_sector]

      capex_shock <-
        scenario$A_capex_dom_tech[NONBIO, bio_sector] *
          scenario$X_bio[bio_sector] -
        REF$A_capex_dom_tech[NONBIO, bio_sector] *
          REF$X_bio[bio_sector]

      recurrent_total <-
        as.numeric(L_NN %*% recurrent_shock)

      capex_total <-
        as.numeric(L_NN %*% capex_shock)

      total_effect <- recurrent_total + capex_total

      out[[counter]] <- data.frame(
        year = as.integer(year),
        scenario = scenario_name,
        bio_sector_id = bio_sector,
        biofuel = get_fuel_name(bio_sector),
        fuel_group = get_fuel_group(bio_sector),

        fuel_market_value_REF = REF$X_bio[bio_sector],
        fuel_market_value_scenario = scenario$X_bio[bio_sector],
        fuel_market_value_change =
          scenario$X_bio[bio_sector] - REF$X_bio[bio_sector],

        recurrent_first_order_contribution = sum(recurrent_shock),
        capex_first_order_contribution = sum(capex_shock),
        first_order_contribution =
          sum(recurrent_shock) + sum(capex_shock),

        recurrent_higher_order_contribution =
          sum(recurrent_total) - sum(recurrent_shock),
        capex_higher_order_contribution =
          sum(capex_total) - sum(capex_shock),
        higher_order_contribution =
          sum(total_effect) -
          sum(recurrent_shock) -
          sum(capex_shock),

        recurrent_total_NONBIO_contribution = sum(recurrent_total),
        capex_total_NONBIO_contribution = sum(capex_total),
        total_NONBIO_contribution = sum(total_effect)
      )

      counter <- counter + 1
    }


    
  }

  do.call(rbind, out)
}

