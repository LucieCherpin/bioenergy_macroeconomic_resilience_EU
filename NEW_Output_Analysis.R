      exports <- sum(s$exports[BIO])

      out[[counter]] <- data.frame(
        year = scenario$years[i],
        scenario = scenario_name,
        recurrent_domestic_input_level = dom_rec,
        recurrent_imported_input_level = imp_rec,
        recurrent_import_share = safe_ratio(imp_rec, dom_rec + imp_rec),
        recurrent_import_change_vs_REF = imp_rec - ref_imp_rec,
