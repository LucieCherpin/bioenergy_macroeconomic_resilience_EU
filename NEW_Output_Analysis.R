# 11. NONBIO OUTPUT DECOMPOSITION:
#     RECURRENT DIRECT + CAPEX DIRECT + HIGHER-ORDER
# ===================================================================

decompose_NONBIO_output <- function(scenario, ref) {
  A_NN_ref <- ref$A_dom_tech[NONBIO, NONBIO, drop = FALSE]

  stopifnot(
    isTRUE(
      all.equal(
        scenario$A_dom_tech[NONBIO, NONBIO, drop = FALSE],
        A_NN_ref,
        tolerance = 1e-10
      )
    )
  )

  L_NN <- solve(
    base::diag(length(NONBIO)) - A_NN_ref
  )

  recurrent_scenario <-
    scenario$A_dom_tech[NONBIO, BIO, drop = FALSE] %*%
    scenario$X_bio[BIO]

  recurrent_ref <-
    ref$A_dom_tech[NONBIO, BIO, drop = FALSE] %*%
    ref$X_bio[BIO]

  recurrent_shock <- recurrent_scenario - recurrent_ref

  capex_shock <-
    scenario$GFCF_capex_delta[NONBIO] -
    ref$GFCF_capex_delta[NONBIO]

  direct_shock <-
    as.numeric(recurrent_shock) +
    as.numeric(capex_shock)

  recurrent_total_effect <-
    as.numeric(L_NN %*% recurrent_shock)

  capex_total_effect <-
    as.numeric(L_NN %*% capex_shock)

  reconstructed_total_effect <-
    recurrent_total_effect + capex_total_effect

  actual_total_effect <-
    scenario$X[NONBIO] - ref$X[NONBIO]

  stopifnot(
    isTRUE(
      all.equal(
        reconstructed_total_effect,
        as.numeric(actual_total_effect),
        tolerance = 1e-8
      )
    )
  )

  data.frame(
    recurrent_first_order_output = sum(recurrent_shock),
    capex_first_order_output = sum(capex_shock),
    total_first_order_output = sum(direct_shock),

    recurrent_higher_order_output =
      sum(recurrent_total_effect) - sum(recurrent_shock),
    capex_higher_order_output =
      sum(capex_total_effect) - sum(capex_shock),
    total_higher_order_output =
      sum(reconstructed_total_effect) - sum(direct_shock),

    recurrent_total_NONBIO_output = sum(recurrent_total_effect),
    capex_total_NONBIO_output = sum(capex_total_effect),
    total_NONBIO_output = sum(actual_total_effect)
  )
}

calculate_NONBIO_decomposition <- function(year_results, year) {
  REF <- year_results$REF

