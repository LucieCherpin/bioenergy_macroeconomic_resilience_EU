# 5. AGGREGATE OUTPUT AND GVA EFFECTS: SCENARIO VS REF
# ===================================================================

calculate_macro_summary <- function(year_results, year) {
  REF <- year_results$REF

  out <- lapply(
    scenario_names,
    function(scenario_name) {
      scenario <- year_results[[scenario_name]]

      delta_X   <- scenario$X   - REF$X
      delta_GVA <- scenario$GVA - REF$GVA

      data.frame(
        year = as.integer(year),
        scenario = scenario_name,

        ref_total_output = sum(REF$X),
        scenario_total_output = sum(scenario$X),
        total_output_change = sum(delta_X),
        total_output_change_pct =
          100 * safe_ratio(sum(delta_X), sum(REF$X)),

        bio_output_change = sum(delta_X[BIO]),
        nonbio_output_change = sum(delta_X[NONBIO]),

        ref_total_GVA = sum(REF$GVA),
        scenario_total_GVA = sum(scenario$GVA),
        total_GVA_change = sum(delta_GVA),
        total_GVA_change_pct =
          100 * safe_ratio(sum(delta_GVA), sum(REF$GVA)),

        bio_GVA_change = sum(delta_GVA[BIO]),
        nonbio_GVA_change = sum(delta_GVA[NONBIO])
      )
    }
  )

  do.call(rbind, out)
}

macro_summary_all <- do.call(
  rbind,
  lapply(
    benchmark_years,
    function(year) {
      calculate_macro_summary(results[[year]], year)
    }
  )
