# ===================================================================
# 16. S2 VS S3: SYMMETRIC SCALE / RECURRENT-TECH / CAPEX-TECH DECOMPOSITION
# ===================================================================
#
# For NONBIO output:
#   X_N = L_NN [Y_base + A_rec X_B + A_cap X_B - K_2023]
#
# Between S2 and S3, Y_base and K_2023 cancel. We use the exact
# symmetric decomposition:
#
# A3 x3 - A2 x2 =
#   0.5 (A2 + A3)(x3 - x2)          [scale]
# + 0.5 (A3 - A2)(x3 + x2)          [technology]
#
# and split technology into recurrent and CAPEX coefficient effects.
# ===================================================================

calculate_S2_S3_decomposition <- function(year_results, year) {
  S2 <- year_results$S2
  S3 <- year_results$S3

  A_NN <- S2$A_dom_tech[NONBIO, NONBIO, drop = FALSE]

  stopifnot(
    isTRUE(
      all.equal(
        A_NN,
        S3$A_dom_tech[NONBIO, NONBIO, drop = FALSE],
        tolerance = 1e-10
      )
    )
  )

  L_NN <- solve(base::diag(length(NONBIO)) - A_NN)

  Arec2 <- S2$A_dom_tech[NONBIO, BIO, drop = FALSE]
  Arec3 <- S3$A_dom_tech[NONBIO, BIO, drop = FALSE]

  Acap2 <- S2$A_capex_dom_tech[NONBIO, BIO, drop = FALSE]
  Acap3 <- S3$A_capex_dom_tech[NONBIO, BIO, drop = FALSE]

  x2 <- S2$X_bio[BIO]
  x3 <- S3$X_bio[BIO]

  scale_direct <-
    0.5 * (
      (Arec2 + Acap2) +
      (Arec3 + Acap3)
    ) %*% (x3 - x2)

  recurrent_technology_direct <-
    0.5 * (Arec3 - Arec2) %*% (x3 + x2)

  capex_technology_direct <-
    0.5 * (Acap3 - Acap2) %*% (x3 + x2)

  scale_total <- as.numeric(L_NN %*% scale_direct)
  recurrent_technology_total <-
    as.numeric(L_NN %*% recurrent_technology_direct)
  capex_technology_total <-
    as.numeric(L_NN %*% capex_technology_direct)

  reconstructed_difference <-
    scale_total +
    recurrent_technology_total +
    capex_technology_total

  actual_difference <-
    S3$X[NONBIO] - S2$X[NONBIO]

  stopifnot(
    isTRUE(
      all.equal(
        reconstructed_difference,
        as.numeric(actual_difference),
        tolerance = 1e-8
      )
    )
  )

  aggregate_row <- data.frame(
    year = as.integer(year),

    scale_first_order = sum(scale_direct),
    scale_higher_order = sum(scale_total) - sum(scale_direct),
    scale_total_effect = sum(scale_total),

    recurrent_technology_first_order =
      sum(recurrent_technology_direct),
    recurrent_technology_higher_order =
      sum(recurrent_technology_total) -
      sum(recurrent_technology_direct),
    recurrent_technology_total_effect =
      sum(recurrent_technology_total),

    capex_technology_first_order =
      sum(capex_technology_direct),
    capex_technology_higher_order =
      sum(capex_technology_total) -
      sum(capex_technology_direct),
    capex_technology_total_effect =
      sum(capex_technology_total),

    total_S3_minus_S2_NONBIO = sum(actual_difference),
    decomposition_check =
      sum(reconstructed_difference) - sum(actual_difference)
  )

  sector_rows <- data.frame(
    year = as.integer(year),
    sector_id = NONBIO,
    sector = sector_names[NONBIO],
    scale_effect = scale_total,
    recurrent_technology_effect = recurrent_technology_total,
    capex_technology_effect = capex_technology_total,
    reconstructed_S3_minus_S2 = reconstructed_difference,
    actual_S3_minus_S2 = as.numeric(actual_difference)
  )

  list(
    aggregate = aggregate_row,
    sector = sector_rows
  )
}

