# Annual import/trade path
calculate_annual_import_trade_path <- function(dynamic_results) {
  REF <- dynamic_results$REF

  out <- list()
  counter <- 1

  for (scenario_name in scenario_names) {
    scenario <- dynamic_results[[scenario_name]]

    for (i in seq_along(scenario$years)) {
      year_char <- as.character(scenario$years[i])

      # Reconstruct a lightweight endpoint from annual arrays.
      s <- list(
        A_dom_tech = scenario$A_dom_tech[year_char, , ],
        A_imp_tech = scenario$A_imp_tech[year_char, , ],
        A_capex_dom_tech = scenario$A_capex_dom_tech[year_char, , ],
        A_capex_imp_tech = scenario$A_capex_imp_tech[year_char, , ],
        X_bio = scenario$X_bio[year_char, ],
        Y_imp_FCE = scenario$Y_imp_FCE[year_char, ],
        exports = scenario$exports[year_char, ]
      )

      r <- list(
        A_dom_tech = REF$A_dom_tech[year_char, , ],
        A_imp_tech = REF$A_imp_tech[year_char, , ],
        A_capex_dom_tech = REF$A_capex_dom_tech[year_char, , ],
        A_capex_imp_tech = REF$A_capex_imp_tech[year_char, , ],
        X_bio = REF$X_bio[year_char, ],
        Y_imp_FCE = REF$Y_imp_FCE[year_char, ],
        exports = REF$exports[year_char, ]
      )

      dom_rec <- sum(get_domestic_recurrent_demand(s))
